# =========================================================
# IMPORT LIBRARIES
# =========================================================

import torch
import torch.nn as nn



class ANNModel(nn.Module):

    # -----------------------------------------------------
    # CONSTRUCTOR
    # -----------------------------------------------------
    def __init__(self):

        # Initialize parent class
        super(ANNModel, self).__init__()

        # =================================================
        # NETWORK ARCHITECTURE
        # =================================================

        self.model = nn.Sequential(

            # -------------------------------------------------
            # FLATTEN LAYER
            # -------------------------------------------------
            # Converts:
            # [3,128,128]
            # →
            # [49152]
            # -------------------------------------------------
            nn.Flatten(),

            # -------------------------------------------------
            # FIRST FULLY CONNECTED LAYER
            # -------------------------------------------------
            nn.Linear(3 * 128 * 128, 512),

            # Activation function
            nn.ReLU(),

            # Dropout helps prevent overfitting
            nn.Dropout(0.3),

            # -------------------------------------------------
            # SECOND FULLY CONNECTED LAYER
            # -------------------------------------------------
            nn.Linear(512, 128),

            nn.ReLU(),

            nn.Dropout(0.3),

            # -------------------------------------------------
            # OUTPUT LAYER
            # -------------------------------------------------
            # 2 output classes:
            # ok
            # not_ok
            # -------------------------------------------------
            nn.Linear(128, 2)
        )

    # -----------------------------------------------------
    # FORWARD PASS
    # -----------------------------------------------------
    # Defines how data flows through network
    # -----------------------------------------------------
    def forward(self, x):

        return self.model(x)


